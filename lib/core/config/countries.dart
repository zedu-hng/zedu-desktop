/// Returns the country name for [value]: a two-letter ISO code such as `za`
/// or `NG` becomes its name in [kCountries], and anything else, a full name
/// or an unknown code, comes back unchanged (#2081).
String countryDisplayName(String value) {
  final trimmed = value.trim();
  if (trimmed.length != 2) return value;
  return kCountryNamesByCode[trimmed.toUpperCase()] ?? value;
}
